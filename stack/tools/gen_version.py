"""stack_version.h from stack/VERSION, for every kind of build (the device, the simulator, the browser emulator):

    tools/gen_version.py OUT/stack_version.h

The version is written in one place, stack/VERSION. A release build's --release takes the same file (the workflow),
and base/tools/build.py passes it in capitals; so does this."""
import sys
from pathlib import Path

version = (Path(__file__).resolve().parent.parent / "VERSION").read_text().strip().upper()
Path(sys.argv[1]).write_text("/* GENERATED by tools/gen_version.py from stack/VERSION: do not edit. */\n"
                             f'#define STACK_VERSION "{version}"\n')
