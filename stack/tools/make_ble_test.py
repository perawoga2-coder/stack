"""Writes app/tests/ble.txt: Bluetooth MIDI in the host simulator (its stand-in for the radio: "ble connect").

    python3 tools/make_ble_test.py > app/tests/ble.txt
"""
L = []


def many(*lines):
    L.extend(lines)


def bt_ticks(n, gap=20):
    """n clock ticks in over Bluetooth, gap ms apart (a message takes 2 ms of the script's time)"""
    for _ in range(n):
        many("midi BLE F8 00 00", f"wait {gap - 2}")


many("# STACK in the host simulator: Bluetooth MIDI (docs/PROTOCOL.md).",
     "# GENERATED by tools/make_ble_test.py: do not edit.",
     "#   app/build/host/stack_host app/tests/ble.txt app/build/host",
     "master 4096", "wait 2200",
     "# no link: nothing goes out over Bluetooth, the header shows no BT",
     "expect bt 0", "wait 1000", "expect clk_bt_out 0", "shot ble_none.png",
     "# a tablet connects: BT in the header; the FM-1 leads, so its clock goes out over Bluetooth too (48 ticks a second)",
     "ble connect", "wait 100", "expect bt 1", "shot ble_connected.png",
     "expect clk_follow 0", "wait 2000", "expect clk_bt_out >90", "expect clk_bt_out <105",
     "# a note in over Bluetooth plays the selected track, as one over USB does; no note is ever sent, on either",
     "expect voices 0", "midi BLE 90 3C 64", "wait 50", "expect voices 1", "midi BLE 80 3C 00", "wait 400",
     "midi USB 90 3C 64", "wait 50", "expect voices 1", "midi USB 80 3C 00", "wait 1200", "expect voices 0",
     "expect bt_out 0", "expect notes_out 0",
     "# PLAY: Start goes out on both", "tap PLAY", "wait 300", "expect clk_starts 1", "tap PLAY", "wait 300",
     "expect clk_stops 1",
     "# --- a clock in over Bluetooth (125): the FM-1 follows it, says the cable is steadier, and sends no clock anywhere",
     "expect clk_out_span <100000")
bt_ticks(60)
many("expect clk_follow 1", "expect clk_src 1", "shot ble_clock.png", "expect clk_bpm10 >1240", "expect clk_bpm10 <1260",
     "expect clk_out_span <100000")
bt_ticks(50)
many("expect clk_out_gap 0", "# Start and Stop over Bluetooth", "midi BLE FA 00 00", "wait 18")
bt_ticks(28)
many("expect playing 1", "expect clk_step 4", "midi BLE FC 00 00", "wait 18")
bt_ticks(5)
many("expect playing 0",
     "# a clock on USB meanwhile is left alone (the FM-1 follows the one it took first), and nothing is passed across",
     "clock 10 4", "expect clk_src 1")
bt_ticks(10)
many("expect clk_src 1", "expect bt_out 0", "expect notes_out 0",
     "# the Bluetooth clock stops: the FM-1 leads again",
     "wait 700", "expect clk_follow 0", "expect clk_src -1",
     "# now a clock on USB: followed from there; one on Bluetooth meanwhile is left alone",
     "clock 60 20", "expect clk_follow 1", "expect clk_src 0", "midi BLE F8 00 00", "clock 20 20", "expect clk_src 0",
     "wait 700", "expect clk_follow 0",
     "# the link goes: BT leaves the header, the clock goes on over USB alone",
     "ble disconnect", "wait 100", "expect bt 0", "shot ble_gone.png", "expect clk_out_span <100000", "wait 1000",
     "expect clk_out_span <300", "expect lim_clips 0")
print("\n".join(L))
