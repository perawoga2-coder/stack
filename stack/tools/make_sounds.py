"""STACK 0.1.0-test: the TEMPORARY built-in sound set, written as app/sounds_data.h (16-bit PCM, mono).

    tools/make_sounds.py SOURCES.json OUT.h

Every source is audio only (no preset data, no code of another firmware):
  rock      Maker Hip's own Rock kit (synthesized by Burger Studio's own script)
  hugelton  the Hügelton Sample Pack by Leo Kuroshita (CC0 1.0), made by its CC0 script
  vcsl      Versilian Studios VCSL (CC0 1.0)
  render    audio rendered by Maker Hip from a Felucca preset (credit: Felucca, Leo Kuroshita)
The set is temporary: the real set is chosen after a listening test.
"""
import json, subprocess, sys
import numpy as np


def decode(path, rate):
    cmd = ["ffmpeg", "-v", "error", "-i", path, "-f", "s16le", "-ac", "1"]
    if rate:
        cmd += ["-ar", str(rate)]
    cmd += ["-"]
    return np.frombuffer(subprocess.run(cmd, check=True, capture_output=True).stdout, dtype="<i2").astype(np.float64)


def native_rate(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "stream=sample_rate", "-of", "csv=p=0", path],
                         check=True, capture_output=True, text=True).stdout
    return int(out.strip().splitlines()[0])


def find_loop(x, rate, hz, start_s, len_s):
    """a loop of whole periods of hz that begins near start_s and is about len_s long: the length whose two ends match best"""
    a = int(start_s * rate)
    per = rate / hz
    best = None
    for k in range(max(1, int(len_s * hz * 0.6)), int(len_s * hz * 1.4) + 1):
        L = int(round(k * per))
        if a + L + 64 >= len(x):
            break
        w = min(512, L)
        e = float(np.mean((x[a:a + w] - x[a + L:a + L + w]) ** 2))
        if best is None or e < best[0]:
            best = (e, L)
    L = best[1]
    X = min(256, a)                       # the cross-fade baked into the loop's end
    y = x.copy()
    w = np.linspace(0.0, 1.0, X, endpoint=False)
    y[a + L - X:a + L] = x[a + L - X:a + L] * (1.0 - w) + x[a - X:a] * w
    return y[:a + L], a, a + L


def main(src, out):
    spec = json.load(open(src))
    lines = ["/* SPDX-License-Identifier: MPL-2.0",
             " * Copyright (C) 2026 Maker Hip */",
             "/* GENERATED by tools/make_sounds.py from " + src.split("/")[-1] + ": do not edit.",
             " * STACK 0.1.0-test's TEMPORARY built-in sounds, 16-bit PCM mono. Audio only; each sound's source and",
             " * licence is in its row (app/SOUNDS.md has the list). */", ""]
    rows, total = [], 0
    for i, s in enumerate(spec["sounds"]):
        path = spec["roots"][s["from"]] + "/" + s["file"]
        rate = s.get("rate") or native_rate(path)
        x = decode(path, s.get("rate"))
        n = min(len(x), int(s.get("secs", 99.0) * rate))
        x = x[:n]
        ls = le = 0
        if s.get("cycle"):                 # a single cycle: the whole of it loops
            ls, le = 0, len(x)
        elif s.get("loop"):
            x, ls, le = find_loop(x, rate, s["hz"], s["loop"][0], s["loop"][1])
        else:
            f = min(len(x), int(0.012 * rate))   # a one-shot ends on a short fade
            x[len(x) - f:] *= np.linspace(1.0, 0.0, f)
        pk = float(np.max(np.abs(x))) or 1.0
        x = np.round(x * (s.get("peak", 0.9) * 32767.0 / pk)).astype(np.int16)
        total += 2 * len(x)
        name = f"SND_{i}"
        body = ",".join(str(int(v)) for v in x)
        lines.append(f"static const int16_t {name}[{len(x)}] = {{{body}}};")
        flags = "|".join((["SF_LOOP"] if le else []) + (["SF_DRUM"] if s.get("drum") else []) +
                         (["SF_TEMP"] if s["from"] == "render" else [])) or "0"
        rows.append(f'    {{"{s["name"]}", {name}, {len(x)}u, {ls}u, {le}u, {rate}.0f, {s.get("hz", 261.626):.3f}f, {flags}}},'
                    f'   /* {s["from"]}: {s["file"]} */')
        print(f'{s["name"]:14s} {len(x):6d} frames {2 * len(x) / 1024:6.1f} KiB  {s["from"]}')
    lines += ["", "static const sound_t SOUNDS[] = {"] + rows + ["};", f"#define NSOUNDS {len(rows)}u", ""]
    open(out, "w").write("\n".join(lines))
    print(f"total {total / 1024:.1f} KiB in {len(rows)} sounds -> {out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
