"""app/tests/receive.txt: the messages the Burger Studio app sends to put samples into an FM-1's slots, as a script
for the host simulator, with the answers the app waits for.

    tools/make_receive_test.py app/tests/receive.txt

The messages are made the way the app makes them (Maker Hip's Fm1SampleLink.kt: header, kitHeader, pack7, imaEncode
and write): SMP_INFO, SMP_BEGIN, SMP_WRITE in 256-byte pieces from offset 512, SMP_END with the 480-byte header.
The samples are synthesized here (a tone that falls, short hits, a long tone)."""
import math, sys, zlib
import numpy as np
sys.path.insert(0, __file__.rsplit("/", 1)[0])
import make_sounds as ms

HDR = [0x7D, 0x46, 0x4C]
ZONES, HDR_LEN, DATA_OFF, SLOT = 16, 32 + 16 * 28, 512, 0x14000
NS = 69                                   # the built-in sounds: MY 1 is place NS + 1 in the list


def pack7(b):
    out = []
    for i in range(0, len(b), 7):
        g = b[i:i + 7]
        out.append(sum(((v >> 7) & 1) << j for j, v in enumerate(g)))
        out += [v & 0x7F for v in g]
    return out


def frame(cmd, args):
    return "F0 " + " ".join(f"{v:02X}" for v in HDR + [cmd] + list(args)) + " F7"


def u16(v): return [v & 255, (v >> 8) & 255]
def u32(v): return [(v >> (8 * k)) & 255 for k in range(4)]


def header(name, zones, data, span=1, rate=22050, crc=None):
    """zones: (offset, samples, root, lo, hi)"""
    h = [0] * HDR_LEN
    h[0:4] = u32(0x504D5346)
    h[4:6] = u16(1)
    h[6] = len(zones)
    h[7] = span if span >= 2 else 0
    for k, c in enumerate(name.upper()[:8]):
        h[8 + k] = ord(c)
    h[16:20] = u32(len(data))
    h[20:24] = u32(zlib.crc32(bytes(data)) if crc is None else crc)
    for k, (off, n, root, lo, hi) in enumerate(zones):
        z = 32 + 28 * k
        h[z:z + 4] = u32(off)
        h[z + 4:z + 8] = u32(n)
        h[z + 12:z + 16] = u32(n - 1)
        h[z + 16:z + 20] = u32(round(rate / 44100.0 * 65536))
        h[z + 20:z + 22] = u16(root * 16)
        h[z + 25], h[z + 26] = lo, hi
    return h


def upload(L, slot, hdr, data, end_rc=0, stop_after=None):
    """the app's write(): INFO, BEGIN, the WRITEs, END; each answer checked"""
    L += ["sysex_out", "sysex " + frame(15, []), "sysex " + frame(11, [slot]), "expect_sysex " + frame(11, [slot, 0]),
          "expect receiving 1"]
    off, n = 0, 0
    while off < len(data):
        e = min(off + 256, len(data))
        a = DATA_OFF + off
        o3 = [a & 0x7F, (a >> 7) & 0x7F, (a >> 14) & 0x7F]
        L += ["sysex " + frame(12, [slot] + o3 + pack7(data[off:e])), "expect_sysex " + frame(12, [slot] + o3 + [0])]
        off = e
        n += 1
        if n % 60 == 0:
            L += ["wait 20"]
        if stop_after and n >= stop_after:
            return
    L += ["sysex " + frame(13, [slot] + pack7(hdr)), "expect_sysex " + frame(13, [slot, end_rc]), "expect receiving 0"]


def expected_gain(x16, rate):
    """the gain the firmware should find: tools/make_sounds.py's loudness of the decoded sample, to TARGET_DB"""
    _, dec, _ = ms.ima_encode(x16)
    db = ms.loudness_db(dec.astype(np.float64) / 32768.0, rate)
    return min(10.0 ** ((ms.TARGET_DB - db) / 20.0), 0.89 * 32768.0 / float(np.max(np.abs(dec))))


def tone(secs, f0, f1, decay, rate=22050, peak=30000):
    t = np.arange(int(secs * rate)) / rate
    f = f0 * (f1 / f0) ** (t / secs)
    x = np.sin(2 * np.pi * np.cumsum(f) / rate) * np.exp(-t / decay)
    return np.round(x / np.max(np.abs(x)) * peak).astype(np.int16)


def main(out):
    L = ["# STACK in the host simulator: samples coming in from the Burger Studio app, as the app sends them.",
         "# GENERATED by tools/make_receive_test.py: do not edit.",
         "#   app/build/host/stack_host app/tests/receive.txt app/build/host",
         "master 4096", "wait 600",
         "# nothing there yet: three empty slots of 80 KiB",
         "sysex_out", "sysex " + frame(15, []),
         "expect_sysex " + frame(15, [3, 80] + [0, 0, 0] * 3 + [1, 1, 1]),
         "sysex " + frame(114, []),
         "expect my1 0", "expect trk7 0", "expect trk8 0",
         "# a WRITE with no BEGIN is refused", "sysex " + frame(12, [0, 0, 4, 0] + pack7([1, 2, 3])),
         "expect_sysex " + frame(12, [0, 0, 4, 0, 4])]
    # 1: a sample into MY 1: it goes onto the empty track 7
    kick = tone(0.5, 180.0, 45.0, 0.12)
    data, _, _ = ms.ima_encode(kick)
    data = list(data)
    L += ["# MY 1 KICK: 0.5 s, onto track 7 (empty)"]
    upload(L, 0, header("KICK", [(0, len(kick), 60, 0, 127)], data), data)
    g1 = expected_gain(kick, 22050)
    L += ["wait 60", "shot receive_my1.png", "expect my1 1", f"expect trk7 {NS + 1}", "expect trk8 0",
          "sysex_out", "sysex " + frame(15, []),
          "expect_sysex " + frame(15, [3, 80, 1] + [ord(c) for c in "KICK"] + [0, len(data) // 1024] + [0, 0, 0] * 2 + [1, 1, 1]),
          "sysex " + frame(112, [0, 0, 1, 3]), "expect_sysex " + frame(112, [0, 0]),
          "wait 600", f"expect my_gain1 >{int(g1 * 100 * 0.88)}", f"expect my_gain1 <{int(g1 * 100 * 1.12) + 1}",
          "turn ALGO 6", "wait 30", "expect track 7", f"expect sound {NS + 1}",
          "wav my1_kick.wav", "key 7 down 100", "wait 300", "expect voices >0", "key 7 up", "wait 400", "wavstop",
          "expect peak_db_min -30", "expect lim_clips 0",
          "# the EDIT page on a sample of the app's (its loudness is measured: it can start part way and play backwards)",
          "tap EDIT", "wait 40", "turn K1 50", "wait 40", "key 7 down 100", "wait 20", "expect v_ed 1", "expect v_ni >5500",
          "key 7 up", "wait 400", "turn K2 1", "wait 40", "wav my1_kick_reverse.wav", "key 7 down 100", "wait 20",
          "expect v_ed 3", "expect v_ni >9000", "expect v_ni <11025", "wait 100", "key 7 up", "wait 400", "wavstop", "expect peak_db_min -40",
          "turn K2 -1", "turn K1 -50", "wait 40", "expect ed_start 0", "expect ed_rev 0", "tap EDIT", "wait 40", "expect page 0"]
    # 2: a kit of four hits into MY 2: onto track 8; each hit on its own key from C4
    hits = [tone(0.15, f, f * 0.6, 0.04) for f in (200.0, 420.0, 900.0, 1800.0)]
    kd, zones = [], []
    for k, h in enumerate(hits):
        d, _, _ = ms.ima_encode(h)
        zones.append((len(kd), len(h), 60 + k, 60 + k, 60 + k))
        kd += list(d)
    L += ["# MY 2 KIT: four hits, onto track 8 (empty); its keys are C4, C#4, D4, D#4"]
    upload(L, 1, header("KIT", zones, kd), kd)
    L += ["wait 60", "expect my2 4", f"expect trk8 {NS + 2}", f"expect trk7 {NS + 1}", "turn ALGO 1", "wait 30", "expect track 8",
          "wait 400", "wav my2_kit.wav"]
    for key in (7, 8, 9, 10):
        L += [f"key {key} down 100", "wait 60", "expect voices >0", f"key {key} up", "wait 240"]
    L += ["wavstop", "wait 600", "key 6 down 100", "wait 60", "expect voices 0", "key 6 up", "wait 60"]
    # 3: a third sample: both tracks are in use, so it only joins the list
    snare = tone(0.3, 900.0, 300.0, 0.06)
    sd, _, _ = ms.ima_encode(snare)
    sd = list(sd)
    L += ["# MY 3 SNARE: tracks 7 and 8 are in use: it is only in the list"]
    upload(L, 2, header("SNARE", [(0, len(snare), 60, 0, 127)], sd), sd)
    L += ["wait 60", "shot receive_in_list.png", "expect my3 1", f"expect trk7 {NS + 1}", f"expect trk8 {NS + 2}"]
    # 4: a transfer whose data does not match its header: refused, the slot is left empty
    L += ["# a damaged transfer (the header's CRC is not the data's): refused"]
    upload(L, 2, header("BAD", [(0, len(snare), 60, 0, 127)], sd, crc=0x12345678), sd, end_rc=3)
    L += ["wait 60", "shot receive_refused.png", "expect my3 0", f"expect trk7 {NS + 1}", f"expect trk8 {NS + 2}"]
    # 5: a transfer that stops half way: after 5 s the slot is given up, empty
    L += ["# a transfer that stops half way: given up after 5 s"]
    upload(L, 2, header("HALF", [(0, len(snare), 60, 0, 127)], sd), sd, stop_after=5)
    L += ["expect receiving 1", "wait 5300", "expect receiving 0", "shot receive_stopped.png", "expect my3 0",
          "sysex_out", "sysex " + frame(13, [2] + pack7(header("HALF", [(0, len(snare), 60, 0, 127)], sd))),
          "expect_sysex " + frame(13, [2, 1])]
    # 6: MY 1 sent again while track 7 holds a note of it: the note ends, the track plays the new sample
    L += ["# MY 1 sent again while track 7 plays it", "turn ALGO -1", "wait 30", "expect track 7", "key 7 down 100", "wait 40",
          "expect voices >0"]
    upload(L, 0, header("SNARE", [(0, len(snare), 60, 0, 127)], sd), sd)
    L += ["key 7 up", "wait 60", "shot receive_again.png", "expect my1 1", f"expect trk7 {NS + 1}"]
    # 7: a long sample over MY 2 and MY 3: the kit goes, MY 3 is part of MY 2's sample
    long = tone(9.0, 220.0, 220.0, 30.0)
    ld, _, _ = ms.ima_encode(long)
    ld = list(ld)
    L += ["# a 9 s sample from MY 2 over MY 3 (two slots)"]
    upload(L, 1, header("LONG", [(0, len(long), 60, 0, 127)], ld, span=2), ld)
    L += ["wait 60", "expect my2 1", "expect my3 0", f"expect trk8 {NS + 2}", "sysex_out", "sysex " + frame(15, []),
          "expect_sysex " + frame(15, [3, 80, 1] + [ord(c) for c in "SNARE"] + [0, len(sd) // 1024, 1] + [ord(c) for c in "LONG"] +
                                  [0, min(127, len(ld) // 1024), 0, 0, 0, 1, 2, 0x41]),
          "turn ALGO 1", "wait 30", "turn PRESET 1", "wait 40", f"expect sound {NS + 3}", "shot receive_joined.png",
          "turn PRESET -1", "wait 40", "wav my2_long.wav", "key 7 down 100", "wait 8600", "expect voices >0", "wait 700",
          "expect voices 0", "key 7 up", "wavstop",
          "# a WRITE past the last slot's end is refused",
          "sysex_out", "sysex " + frame(11, [2]), "expect_sysex " + frame(11, [2, 0])]
    a = SLOT - 0x1000
    L += ["sysex " + frame(12, [2, a & 0x7F, (a >> 7) & 0x7F, (a >> 14) & 0x7F] + pack7([0] * 256)),
          "expect_sysex " + frame(12, [2, a & 0x7F, (a >> 7) & 0x7F, (a >> 14) & 0x7F, 1]),
          "wait 5300", "expect receiving 0",
          "# the samples stay over a power cycle (the tracks start as always: nothing is saved yet)",
          "reboot", "wait 600", "expect my1 1", "expect my2 0", "expect my3 0", "expect trk7 0",
          "sysex_out", "sysex " + frame(15, []),
          "expect_sysex " + frame(15, [3, 80, 1] + [ord(c) for c in "SNARE"] + [0, len(sd) // 1024] + [0, 0, 0] * 2 + [1, 1, 1]),
          "wait 3500", "shot boot_my_samples.png", "expect my_crc1 1",
          "# 0.2.2-test: on the FM-1, 0.2.1-test found every slot empty after a power cycle. The slots are taken by",
          "# their headers now and the scan runs again after the start. A flash that cannot be read during the start:",
          "expect my_blind 1", "reboot", "wait 200", "expect my1 0", "expect my_why1 9", "expect my_sees 1",
          "wait 1200", "expect my1 1", "expect my_why1 0",
          "# a power-off and on (not only a restart)",
          "power", "wait 3600", "expect my1 1", "expect my_crc1 1",
          "# data that no longer matches its header's CRC: the sample stays in the list, its name marked",
          f"data_write {0xA0000 + 512 + 64} 0000000000000000", "reboot", "wait 300", "expect my1 1", "wait 3600",
          "expect my_crc1 2", "turn ALGO 6", "wait 30", f"turn PRESET {NS + 1}", "wait 60", "shot my_crc_marked.png",
          "# a header that is not one: refused, and the list says what was found",
          f"data_erase {0xA0000}", "reboot", "wait 300", "expect my1 0", "expect my_why1 1",
          f"data_write {0xA0000} 4142434445464748", "reboot", "wait 300", "expect my1 0", "expect my_why1 2",
          "turn ALGO 6", "wait 30", f"turn PRESET {NS + 1}", "wait 60", "shot my_refused.png",
          "expect lim_clips 0", "expect store_writes 0"]
    open(out, "w").write("\n".join(L) + "\n")
    print(f"{out}: {len(L)} lines; MY 1's gain should come to {g1:.2f}")


def keys(out, folder):
    """app/tests/keys.txt and its two .bin files: a slot that held something else, then one sample: every key plays it"""
    import random
    rnd = random.Random(20261124)
    # an old kit of 16 hits, its header whole (as an earlier transfer or another firmware left it), noise as its audio
    old = [rnd.randrange(256) for _ in range(3200)]
    head = header("OLDKIT", [(200 * k, 400, 60 + k, 60 + k, 60 + k) for k in range(16)], old)
    blob = bytes(head) + bytes([0xFF] * (512 - len(head))) + bytes(old)
    blob += bytes(rnd.randrange(256) for _ in range(4096 - len(blob)))
    open(folder + "/junk_head.bin", "wb").write(blob)
    # the slot's last 4 KiB: a made-up table, as a firmware that keeps its slices there would leave one
    open(folder + "/junk_tail.bin", "wb").write(b"SLC1" + bytes(rnd.randrange(256) for _ in range(4092)))
    L = ["# STACK in the host simulator: a slot that held something else before (an old 16-hit kit's header and audio at its",
         "# start, a table in its last 4 KiB), then one sample from the app: every key plays that sample and nothing else.",
         "# GENERATED by tools/make_receive_test.py: do not edit.",
         "#   app/build/host/stack_host app/tests/keys.txt app/build/host     (run from the stack/ folder: the .bin files)",
         "master 4096", "wait 300",
         "data app/tests/junk_head.bin 0xA0000", "data app/tests/junk_tail.bin 0xB3000",
         "reboot", "wait 1500", "# the old kit is what the slot holds (its header is whole): 16 hits", "expect my1 16",
         "# one sample from the app into that slot"]
    kick = tone(0.5, 180.0, 45.0, 0.12)
    data, _, _ = ms.ima_encode(kick)
    data = list(data)
    upload(L, 0, header("KICK", [(0, len(kick), 60, 0, 127)], data), data)
    L += ["wait 100", "expect my1 1", f"expect trk7 {NS + 1}", "turn ALGO 6", "wait 30", "expect track 7", "turn K3 -95", "wait 30",
          "# every key of the 27, at the keys' middle, highest and lowest octaves: one voice of the sample, no MIDI out"]
    for octave, button, taps in ((0, None, 0), (2, "OCT+", 2), (-2, "OCT-", 4)):
        for _ in range(taps):
            L += [f"tap {button}", "wait 30"]
        L += [f"expect octave {octave}"]
        for k in range(27):
            L += [f"key {k} down 100", "wait 30", "expect voices 1", f"key {k} up", "wait 250", "expect voices 0"]
    L += ["# (the clock goes out since 0.4.2: what is checked is that no note does)", "expect notes_out 0", "tap OCT+", "wait 30", "tap OCT+", "wait 30", "expect octave 0", "wav keys_all.wav"]
    for k in range(27):
        L += [f"key {k} down 100", "wait 120", f"key {k} up", "wait 60"]
    L += ["wavstop", "expect lim_clips 0", "# held past its end, the sample stops: nothing after it is played",
          "key 26 down 100", "wait 900", "expect voices 0", "key 26 up", "key 0 down 100", "wait 1500", "expect voices 0",
          "key 0 up", "expect store_writes 0"]
    open(out, "w").write("\n".join(L) + "\n")
    print(f"{out}: {len(L)} lines")


if __name__ == "__main__":
    main(sys.argv[1])
    keys(sys.argv[1].rsplit("/", 1)[0] + "/keys.txt", sys.argv[1].rsplit("/", 1)[0])
