"""Writes app/tests/dump.txt: the dump for the app's VACUUM (app/dump.c, docs/PROTOCOL.md) in the host simulator.

The song's record is made here too, from tools/sounds.json and the tracks' starting values, byte for byte as the
protocol says, and every piece STACK sends is checked against it.

    python3 tools/make_dump_test.py > app/tests/dump.txt
"""
import json, os, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
CATS = ["DRUMS", "BASS", "KEYS", "PAD", "LEAD", "FX"]
spec = json.load(open(os.path.join(HERE, "sounds.json")))["sounds"]
SOUNDS = [spec[i] for i in sorted(range(len(spec)), key=lambda i: (CATS.index(spec[i]["cat"]), i))]
VERSION = open(os.path.join(HERE, "..", "VERSION")).read().strip().upper()
PIECE, HEAD, TRK = 128, 32, 96
L = []


def many(*lines):
    L.extend(lines)


def name_hash(n):
    h = 0x811C9DC5
    for c in n.encode():
        h = ((h ^ c) * 0x01000193) & 0xFFFFFFFF
    return h + 16 if h < 16 else h


def track(kind="", name=None, **over):
    """a track as it starts, with what the test changed"""
    s = next((x for x in SOUNDS if x["name"] == name), None)
    drum = bool(s and s.get("drum"))
    f = dict(pitch=0, filt=0, decay=50 if s and not drum else 100, level=80, env_a=0, env_r=-1, env_s=100, env_v=75,
             lfo_a=0, lfo_r=6, lfo_t=0, lfo_s=0, ed_start=0, ed_rev=0, ed_loop=0, ed_len=100, fit=0, arp_r=0, arp_m=0,
             arp_o=1, arp_g=50, fxa=0, fxb=0, fxak=0, fxbk=0)
    steps = over.pop("steps", {})
    f.update(over)
    p = bytearray(TRK)
    p[1] = 255
    text, cat = "", ""
    if kind == "LOOP":
        p[0], text, cat = 3, "LOOP", "LOOP"
    elif s:
        p[0], p[1] = 1, CATS.index(s["cat"])
        p[3] = (1 if drum else 0) | (2 if s.get("loop") or s.get("cycle") else 0)
        p[4:8] = name_hash(name).to_bytes(4, "little")
        text, cat = name, s["cat"]
    p[12:12 + len(text)] = text.encode()
    p[88:88 + len(cat)] = cat.encode()
    for i, k in enumerate(f):
        p[28 + i] = f[k] & 255
    for i in range(16):
        p[56 + i] = 1 if i in steps else 0
        p[72 + i] = steps.get(i, 60)
    return bytes(p)


def song(tracks, bpm=120, sig=2, steps=16, swing=50, sel=0, layers=0, flags=0):
    b = bytearray(HEAD)
    b[0:4] = b"STKD"
    b[4], b[5], b[6], b[7] = 1, 8, TRK, flags
    n = HEAD + 8 * TRK
    b[8:10] = n.to_bytes(2, "little")
    b[16], b[17], b[18], b[19], b[20], b[21] = bpm, sig, steps, swing, sel, layers
    b[22:22 + len(VERSION[:10])] = VERSION[:10].encode()
    b += b"".join(tracks)
    b[10:14] = zlib.crc32(bytes(b[16:])).to_bytes(4, "little")
    return bytes(b)


def pack7(d):
    o = []
    for i in range(0, len(d), 7):
        c = d[i:i + 7]
        o.append(sum((x >> 7) << j for j, x in enumerate(c)))
        o += [x & 127 for x in c]
    return o


def frame(cmd, body):
    return "F0 7D 46 4C " + " ".join(f"{x:02X}" for x in [cmd] + list(body)) + " F7"


def ask_song(blob):
    pieces = (len(blob) + PIECE - 1) // PIECE
    for k in range(pieces):
        many("sysex_out", "sysex " + frame(30, [k & 127, k >> 7]), "wait 4",
             "expect_sysex " + frame(30, [k & 127, k >> 7, pieces & 127, pieces >> 7] + pack7(blob[k * PIECE:(k + 1) * PIECE])))


START = ["KICK ROCK", "SNARE ROCK", "HAT ROCK", "SUB BASS", "PIANO", "SAW LEAD", None, None]
