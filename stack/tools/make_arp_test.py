"""Writes app/tests/arp.txt: the ARP page in the host simulator.

    python3 tools/make_arp_test.py > app/tests/arp.txt
"""
L = []
A = L.append


def seq(notes):
    """after the keys went down (4 ms ago): the notes heard, one a step of 250 ms"""
    A("wait 56")
    for i, n in enumerate(notes):
        A(f"expect arp_note {n}")
        if i < len(notes) - 1:
            A("wait 250")


def chord(keys=("w0", "w2", "w4")):
    for k in keys:
        A(f"key {k} down 100")


def up(keys=("w0", "w2", "w4")):
    for k in keys:
        A(f"key {k} up")
    A("wait 300")
    A("expect arp_keys 0")
    A("expect arp_note -1")


def many(*lines):
    for x in lines:
        A(x)


many("# STACK in the host simulator: the ARP page (RATE, MODE, OCTAVE, GATE).",
     "# GENERATED by tools/make_arp_test.py: do not edit.",
     "#   app/build/host/stack_host app/tests/arp.txt app/build/host",
     "master 4096", "wait 2200",
     "# the piano on track 5; the keys w0, w2, w4 are the notes 53, 57, 60",
     "turn ALGO 4", "wait 40", "expect track 5",
     "# ARP: its page and back",
     "tap ARP", "wait 40", "expect page 6", "tap ARP", "wait 40", "expect page 0", "tap ARP", "wait 40",
     "# as it starts: OFF (the keys as they are), UP, 1 octave, GATE 50",
     "expect arp_r 0", "expect arp_m 0", "expect arp_o 1", "expect arp_g 50", "shot arp_off.png",
     "key w0 down 100", "key w2 down 100", "wait 60", "expect voices 2", "expect arp_keys 0", "key w0 up", "key w2 up",
     "wait 1200", "expect voices 0",
     "# the knobs stop at their ends")
for knob, name, lo, hi in (("K1", "arp_r", 0, 7), ("K2", "arp_m", 0, 3), ("K3", "arp_o", 1, 3), ("K4", "arp_g", 10, 100)):
    many(f"turn {knob} 150", "wait 40", f"expect {name} {hi}", f"turn {knob} -150", "wait 40", f"expect {name} {lo}")
many("# --- RATE 1/8 (a step every 250 ms at 120), GATE 100, the pattern stopped: UP, from the first key at once",
     "turn K1 3", "turn K4 90", "wait 40", "expect arp_r 3", "expect arp_g 100", "shot arp_up.png", "wav arp_up.wav")
chord()
seq([53, 57, 60, 53, 57, 60])
A("expect voices >0")
up()
many("wavstop", "# DOWN (the top key first: the ARP starts with the first key that goes down)", "turn K2 1", "wait 40",
     "wav arp_down.wav")
chord(("w4", "w2", "w0"))
seq([60, 57, 53, 60, 57])
up()
many("wavstop", "# UP-DOWN: the ends are not played twice", "turn K2 1", "wait 40", "wav arp_updown.wav")
chord()
seq([53, 57, 60, 57, 53, 57, 60])
up()
many("wavstop", "# ORDER: as the keys were pressed", "turn K2 1", "wait 40", "expect arp_m 3", "wav arp_order.wav")
chord(("w2", "w4", "w0"))
seq([57, 60, 53, 57, 60, 53])
up()
many("wavstop", "# OCTAVE 2, UP: the notes, then the same an octave higher", "turn K2 -3", "turn K3 1", "wait 40",
     "expect arp_o 2", "wav arp_two_octaves.wav")
chord()
seq([53, 57, 60, 65, 69, 72, 53])
up()
many("wavstop", "# OCTAVE 3, DOWN: from the top", "turn K2 1", "turn K3 1", "wait 40")
chord(("w2", "w0"))
A("wait 2")
seq([81, 77, 69, 65, 57, 53, 81])
up(("w0", "w2"))
many("turn K2 -1", "turn K3 -2", "wait 40",
     "# GATE 10: a note is let go a tenth of a step in (25 ms)", "turn K4 -90", "wait 40", "expect arp_g 10")
chord()
many("wait 96", "expect arp_note -1", "wait 166", "expect arp_note 57", "wait 60", "expect arp_note -1")
up()
many("turn K4 40", "wait 40", "expect arp_g 50",
     "# a key added while it runs joins in; one let go leaves",
     "key w0 down 100", "key w4 down 100", "wait 100", "expect arp_keys 2", "key w2 down 100", "wait 40",
     "expect arp_keys 3", "key w0 up", "wait 40", "expect arp_keys 2")
up(("w2", "w4"))
A("# RATE to OFF under held keys: they are let go, nothing hangs")
chord()
many("wait 300", "turn K1 -3", "wait 40", "expect arp_r 0", "wait 100", "expect arp_keys 0", "expect arp_note -1",
     "key w0 up", "key w2 up", "key w4 up", "wait 1200", "expect voices 0",
     "# the ARP turned on under a held key: that key's note is let go when the key is",
     "key w4 down 100", "wait 60", "expect voices 1", "turn K1 3", "wait 40", "key w4 up", "wait 1200", "expect voices 0",
     "# --- with the pattern playing it is on the bar's grid: 1/16 is a step of the pattern (125 ms)",
     "turn K1 2", "wait 40", "expect arp_r 5", "tap PLAY", "wait 30")
chord()
many("wait 46", "# (PLAY 110 ms ago: its first step falls on the pattern's second, at 125 ms)",
     "expect arp_steps 1", "wait 125", "expect arp_steps 2", "wait 1000", "expect arp_steps 10")
up()
many("tap PLAY", "wait 100",
     "# --- the looper records it: a take of the ARP, then the loop plays it with no key down",
     "turn K1 -2", "wait 40", "expect arp_r 3",
     "tap PLAY", "wait 100", "wav arp_in_the_loop.wav", "tap REC", "wait 60", "expect loop_state 2")
chord()
many("wait 1200", "tap REC", "wait 400")     # (REC again after 1.3 s: one bar is nearest, it records on to 2 s)
up()
many("wait 800", "expect loop_layers 1", "expect loop_state 0", "expect voices 0", "peakreset", "wait 1500",
     "expect peak_db_min -40", "wavstop", "tap PLAY", "wait 200",
     "# --- under a clock in (125: a tick every 20 ms): 1/8 is 12 ticks, 8 steps in a bar of 96",
     "clock 48 20", "clock 1 18", "midi FA 00 00", "clock 3 20", "clock 1 14")
chord()
many("clock 2 20", "expect arp_steps 0", "clock 6 20", "expect arp_steps 1", "clock 96 20", "expect arp_steps 9",
     "clock 1 14", "key w0 up", "key w2 up", "key w4 up", "clock 20 20", "expect arp_keys 0", "expect arp_note -1",
     "clock 1 18", "midi FC 00 00", "clock 5 20",
     "# another track's ARP is its own: track 1's is off",
     "tap ARP", "wait 40", "turn ALGO -4", "wait 40", "expect track 1", "expect arp_r 0", "expect lim_clips 0")
print("\n".join(L))
