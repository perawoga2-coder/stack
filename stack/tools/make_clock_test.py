"""Writes app/tests/clock.txt: the clock out and in (app/clock.c) in the host simulator.

The simulator's "clock N MS" sends N ticks MS apart, in whole milliseconds, and every other command takes time too
(a button or a message 2 ms), so the script is made here: each tick's time is kept on a grid and what happens between
two ticks is taken out of the gap, as a tablet's clock would go on under it.

    python3 tools/make_clock_test.py > app/tests/clock.txt
"""
import random

random.seed(20261124)
out = []
say = out.append


def ticks(n, gap=20):
    if n > 0:
        say(f"clock {n} {gap}")


def tick_then(*cmds, gap=20):
    """one tick, then cmds (2 ms each) before the next"""
    say(f"clock 1 {gap - 2 * len(cmds)}")
    for c in cmds:
        say(c)


say("# STACK in the host simulator: the clock, out and in (app/clock.c; docs/PROTOCOL.md).")
say("# GENERATED by tools/make_clock_test.py: do not edit.")
say("#   app/build/host/stack_host app/tests/clock.txt app/build/host")
say("master 4096")
say("wait 600")
say("expect clk_out_span <100000")
say("# --- CLOCK OUT: the FM-1 leads from the start, 24 ticks a quarter note at 120 (a tick every 20.83 ms), playing or not")
say("wait 5000")
say("expect clk_follow 0")
say("expect clk_bpm10 1200")
say("expect clk_ticks >260")
say("expect clk_ticks <275")
say("# steady: every gap within 0.15 ms of the others (the simulator's tick is 0.1 ms), whatever the screen does")
say("expect clk_out_gap <21000")
say("expect clk_out_span <150")
say("shot clock_fm1.png")
say("# PLAY: Start goes out, then the ticks from the pattern's first step; STOP: Stop. No note is ever sent")
say("tap PLAY")
say("wait 100")
say("expect clk_starts 1")
say("expect clk_out_span <25000")
say("wait 3000")
say("expect clk_out_gap >20700")
say("expect clk_out_span <150")
say("tap PLAY")
say("wait 100")
say("expect clk_stops 1")
say("expect notes_out 0")
say("# --- CLOCK IN: a clock comes (125: a tick every 20 ms): the FM-1 follows it and sends none of its own")
ticks(48)
say("expect clk_follow 1")
say("expect clk_bpm10 1250")
say("expect clk_out_span <100000")
ticks(100)
say("expect clk_out_gap 0")
say("shot clock_burger.png")
say("expect playing 0")
say("# Start, then ticks: the first tick is step 1; 51 ticks on it is in step 9")
tick_then("midi FA 00 00")
ticks(51)
say("expect playing 1")
say("expect clk_step 8")
say("expect clk_err <100")
say("# the ticks 3 ms early or late, as a tablet's come: the tempo holds within 0.3 beats, the place within 0.1 tick")
pj = 0
for i in range(480):
    j = random.randint(-3, 3)
    say(f"clock 1 {20 + j - pj}")
    pj = j
    if i % 120 == 119:
        say("expect clk_bpm10 >1246")
        say("expect clk_bpm10 <1254")
        say("expect clk_err <100")
say(f"clock 1 {20 - pj}")
say("# (532 ticks since Start: tick 531 is in step 9 of the sixth time round)")
say("expect clk_step 8")
say("# Stop stops; the clock goes on and the FM-1 goes on following")
tick_then("midi FC 00 00")
ticks(24)
say("expect playing 0")
say("expect clk_follow 1")
say("# Continue: on from where it stopped (the next tick is tick 53 of the bar: 12 ticks on, step 11)")
tick_then("midi FB 00 00")
ticks(12)
say("expect playing 1")
say("expect clk_step 10")
say("# Stop, Song Position 4 (sixteenths), Continue: from step 5")
tick_then("midi FC 00 00")
tick_then("midi F2 04 00")
tick_then("midi FB 00 00")
ticks(4)
say("expect playing 1")
say("expect clk_step 4")
say("# Start again: from step 1")
tick_then("midi FA 00 00")
ticks(4)
say("expect clk_step 0")
tick_then("midi FC 00 00")
ticks(5)
say("expect playing 0")
say("# PLAY on the FM-1 while it follows: it plays, at the clock's tempo; nothing is sent (no Start, no tick: no loop)")
tick_then("press PLAY")
tick_then("release PLAY")
ticks(20)
say("expect playing 1")
say("expect clk_step 3")
tick_then("press PLAY")
tick_then("release PLAY")
ticks(5)
say("expect playing 0")
say("expect clk_starts 1")
say("expect clk_stops 1")
say("expect clk_out_gap 0")
say("expect notes_out 0")
say("# --- the clock stops coming while it plays: after 0.5 s the FM-1 leads again, at the tempo it followed, and says so")
tick_then("midi FA 00 00")
ticks(40)
say("wait 400")
say("expect clk_follow 1")
say("wait 200")
say("expect clk_follow 0")
say("expect playing 1")
say("shot clock_lost.png")
say("expect clk_bpm10 >1247")
say("expect clk_bpm10 <1253")
say("expect clk_out_span <100000")
say("wait 2000")
say("# its own clock goes out again, at 125 (20 ms a tick)")
say("expect clk_out_gap >19800")
say("expect clk_out_gap <20200")
say("expect clk_out_span <250")
say("tap PLAY")
say("wait 100")
say("expect playing 0")
say("expect clk_stops 2")
say("# a clock again: followed again")
ticks(30)
say("expect clk_follow 1")
say("# a restart: the FM-1 leads, at 120")
say("reboot")
say("wait 600")
say("expect clk_follow 0")
say("expect clk_bpm10 1200")
say("# --- the looper under a clock in: the organ on track 5, looper mode on")
say("tap SEQ")
say("wait 40")
say("turn ALGO 4")
say("wait 40")
say("turn PRESET 4")
say("wait 60")
say("expect sound 37")
say("tap SEQ")
say("wait 40")
say("press OCT-")
say("press OCT+")
say("wait 60")
say("release OCT+")
say("release OCT-")
say("wait 60")
say("expect loop_mode 1")
ticks(48)
tick_then("midi FA 00 00")
ticks(20)
say("# a take, from the next bar (tick 96); a note held across its end, the loop's point")
tick_then("press OCT+")
tick_then("release OCT+")
ticks(96 - 22 - 1)
say("wav clock_loop.wav")
ticks(40)
say("expect loop_state 2")
tick_then("key 7 down 100")
ticks(80)
say("expect loop_layers 1")
say("expect loop_state 0")
ticks(20)
tick_then("key 7 up")
say("# the loop is a bar of the clock's long: 96 ticks of 20 ms (84 672 frames)")
say("expect loop_total >84600")
say("expect loop_total <84750")
ticks(96 * 3)
say("expect loop_drift 0")
say("expect loop_nudge <1001")
say("# the clock drifts: 0.083 % slower (every 60th tick a millisecond late) for 30 s. The loop holds to the bar by")
say("# playing up to 0.1 % slower; it is not out of time and there is no seam (the WAV)")
for i in range(25):
    ticks(59)
    ticks(1, 21)
say("expect loop_drift 0")
say("expect loop_nudge >0")
say("expect loop_nudge <1001")
say("expect clk_follow 1")
say("wavstop")
say("# a real change of tempo (125 to 114): the loop cannot follow, it is out of time and the screen says so")
ticks(200, 22)
say("expect loop_drift 1")
say("expect loop_has 1")
say("shot clock_tempo_changed.png")
ticks(40, 22)
say("shot clock_loop_out_of_time.png")
print("\n".join(out))
